/** Native browser integration test. Never polyfills or mocks document.modelContext. */
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const root = new URL('..', import.meta.url).pathname;
const server = spawn(process.execPath, ['scripts/serve.mjs'], { cwd: root, env: { ...process.env, OMD_PORT: '4317', OMD_STATIC_DIR: 'dist' }, stdio: ['ignore','pipe','pipe'] });
let browser;
const errors = [];
try {
  await new Promise((resolve,reject) => { server.stdout.once('data', resolve); server.once('error', reject); server.once('exit', code => reject(new Error(`Server exited: ${code}`))); });
  browser = await chromium.launch({ headless: true, args: ['--enable-features=WebMCP,WebMCPTesting', '--enable-experimental-web-platform-features'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, colorScheme: 'light' });
  const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:4317/');
  await page.waitForFunction(() => document.getElementById('agent-status').textContent.includes('37 tools'));
  const call = (name, input = {}) => page.evaluate(async ({name,input}) => {
    const registry = document.modelContext;
    if (!registry?.getTools || !registry?.executeTool) throw new Error('Native document.modelContext discovery/execution unavailable.');
    const tool = (await registry.getTools()).find(t => t.name === `omd_${name}`);
    if (!tool) throw new Error(`Missing native tool: ${name}`);
    // Chrome 151's WebIDL takes a JSON string. Newer drafts take an object;
    // JSON-string arguments are deprecated from Chrome 155 onward.
    const major = Number(navigator.userAgent.match(/(?:Chrome|Chromium)\/(\d+)/)?.[1] ?? 155);
    const value = await registry.executeTool(tool, major < 155 ? JSON.stringify(input) : input);
    if (typeof value === 'string') { try { return JSON.parse(value); } catch { return value; } } return value;
  }, { name, input });
  let notebook = await call('get_notebook');
  for (const b of notebook.blocks) await call('remove_block', { blockId: b.id });
  await call('set_page', { title: 'My verified day', notificationMode: 'toast' });
  assert.equal(await page.locator('#page-title').inputValue(), 'My verified day');
  const checklist = (await call('add_block', { type: 'checklist', title: 'Test tasks' })).block;
  await call('checklist_add', { blockId: checklist.id, text: 'An agent-created task' });
  await page.getByRole('checkbox', { name: 'Complete An agent-created task', exact: true }).check();
  notebook = await call('get_notebook'); assert.ok(notebook.blocks[0].items[0].done);
  await page.locator('#page-title').fill('Written by a person');
  await page.reload(); await page.waitForFunction(() => document.getElementById('agent-status').textContent.includes('37 tools'));
  assert.equal(await page.locator('#page-title').inputValue(), 'Written by a person');
  assert.ok((await call('get_notebook')).blocks[0].items[0].done);
  const outer = (await call('add_block', { type: 'tabs', orientation: 'horizontal', title: 'Chapters' })).block;
  const inner = (await call('add_block', { type: 'tabs', orientation: 'vertical', containerId: outer.tabs[0].id })).block;
  await call('add_block', { type: 'text', text: 'Inside both tab levels', containerId: inner.tabs[0].id });
  assert.equal(await page.getByRole('textbox', { name: 'text content', exact: true }).inputValue(), 'Inside both tab levels');
  const before = (await call('get_notebook')).revision;
  await assert.rejects(() => call('add_block', { type: 'tabs', containerId: inner.tabs[0].id }));
  assert.equal((await call('get_notebook')).revision, before);
  await call('tab_update', { blockId: outer.id, tabId: outer.tabs[1].id, title: 'Work' });
  await page.getByRole('tab', { name: 'Open Work', exact: true }).click();
  assert.equal(await page.getByRole('textbox', { name: 'text content', exact: true }).count(), 0);
  await call('tab_select', { blockId: outer.id, tabId: outer.tabs[0].id });
  const toggle = (await call('add_block', { type: 'toggle', title: 'More thoughts' })).block;
  await call('add_block', { type: 'text', text: 'A tucked-away thought', containerId: toggle.id });
  await page.getByRole('button', { name: 'Collapse More thoughts', exact: true }).click();
  assert.equal(await page.getByRole('textbox', { name: 'text content', exact: true }).count(), 1);
  const accordion = (await call('add_block', { type: 'accordion' })).block;
  await call('accordion_add', { blockId: accordion.id, title: 'Another section' });
  await page.getByRole('button', { name: 'Collapse Another section', exact: true }).click();
  const board = (await call('add_block', { type: 'kanban' })).block;
  const card = (await call('card_add', { blockId: board.id, columnId: board.columns[0].id, title: 'Ship this' })).cardId;
  await page.getByRole('combobox', { name: 'Move card to column' }).selectOption(board.columns[1].id);
  await call('column_move', { blockId: board.id, columnId: board.columns[1].id, index: 0 });
  await call('card_update', { blockId: board.id, cardId: card, patch: { description: 'Tiny next step' } });
  assert.equal((await call('get_notebook')).blocks.find(b => b.id === board.id).columns[0].cards[0].id, card);
  await page.locator('#theme').selectOption('dark'); assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  await page.locator('#theme').selectOption('system'); await page.emulateMedia({ colorScheme: 'dark' });
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  await page.emulateMedia({ colorScheme: 'light' }); await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  const exported = (await call('export_notebook')).json;
  await call('set_page', { title: 'Before replacement' });
  const imported = call('import_notebook', { json: exported });
  await page.getByRole('button', { name: 'Back up & import', exact: true }).click();
  assert.ok((await imported).imported);
  assert.equal(await page.locator('#page-title').inputValue(), 'Written by a person');
  await call('set_page', { title: 'Undo this' }); await call('undo'); assert.equal(await page.locator('#page-title').inputValue(), 'Written by a person');
  await call('redo'); assert.equal(await page.locator('#page-title').inputValue(), 'Undo this');
  const r = (await call('add_block', { type: 'reminder', title: 'Browser test nudge', dueAt: '2020-01-01T00:00:00Z' })).block;
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
  await page.getByText('Reminder: Browser test nudge', { exact: true }).waitFor();
  assert.ok((await call('get_notebook')).blocks.find(b => b.id === r.id).firedAt);
  await page.evaluate(() => navigator.serviceWorker.ready);
  await page.waitForFunction(() => !!navigator.serviceWorker.controller);
  await mkdir(`${root}/test-results`, { recursive: true });
  await page.screenshot({ path: `${root}/test-results/desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Page must not overflow on mobile.');
  await page.screenshot({ path: `${root}/test-results/mobile.png`, fullPage: true });
  await context.setOffline(true); await page.reload();
  assert.equal(await page.locator('#page-title').inputValue(), 'Undo this');
  await page.locator('#page-title').fill('Edited offline');
  await page.reload(); assert.equal(await page.locator('#page-title').inputValue(), 'Edited offline');
  assert.deepEqual(errors, []);
  console.log('Native WebMCP, notebook UI, persistence, mobile, theme, reminders, import/export, and offline reload passed.');
} finally { await browser?.close(); server.kill(); }
